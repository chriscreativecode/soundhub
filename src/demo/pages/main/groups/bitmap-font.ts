export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const GLYPH_ADVANCE = 6;

const GLYPHS = new Map<string, string[]>(
  GLYPH_ROWS.map(([char, rows]) => [char, rows.split(' ')]),
);

const FALLBACK = GLYPHS.get('?')!;

export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * GLYPH_ADVANCE - 1) * scale;
}

/**
 * Draws a run of glyphs as solid pixel blocks. Consecutive lit pixels in a row
 * become one rectangle, which keeps a full attract screen at a few hundred
 * fill calls per frame.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  ctx.fillStyle = color;
  const left = Math.round(x);
  const top = Math.round(y);

  for (let i = 0; i < text.length; i++) {
    const glyph = GLYPHS.get(text[i].toUpperCase()) ?? FALLBACK;
    const originX = left + i * GLYPH_ADVANCE * scale;

    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row];
      let runStart = -1;

      for (let col = 0; col <= GLYPH_W; col++) {
        const lit = col < GLYPH_W && bits[col] === '1';
        if (lit && runStart < 0) {
          runStart = col;
        } else if (!lit && runStart >= 0) {
          ctx.fillRect(
            originX + runStart * scale,
            top + row * scale,
            (col - runStart) * scale,
            scale,
          );
          runStart = -1;
        }
      }
    }
  }
}
